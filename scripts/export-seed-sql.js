/* ===== Brew Book — seed export =====
   Reads the SEED array + ROASTER_PICKS out of js/data.js (which is a plain
   script, not a module) by evaluating it in an isolated function scope, then
   emits supabase/seed.sql — one INSERT per recipe into public.recipes.

   Re-run this whenever you change the seed data in js/data.js:
     node scripts/export-seed-sql.js

   Note: this only carries CATALOG content (name, story, steps, methods, …).
   Per-user state (tried / rating) deliberately does NOT go to the catalog —
   it stays client-side in Phase 1 and moves to user_brews in Phase 2. */

const fs = require('fs');
const path = require('path');

const dataSrc = fs.readFileSync(path.join(__dirname, '..', 'js', 'data.js'), 'utf8');
const { SEED, ROASTER_PICKS } = new Function(dataSrc + '; return { SEED, ROASTER_PICKS };')();

/* SQL literal helpers */
const q = (v) => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const num = (v) => v === null || v === undefined || v === '' ? 'null' : Number(v);
const json = (v) => v === null || v === undefined ? 'null' : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const ts = (ms) => ms ? `to_timestamp(${Math.round(ms / 1000)})` : 'now()';

const cols = [
  'id', 'serial', 'name', 'origin', 'method', 'ratio', 'ratio_label',
  'strength', 'description', 'story', 'bean', 'notes',
  'ingredients', 'steps', 'methods', 'roaster_picks', 'created_at'
];

const rows = SEED.map((r) => {
  const picks = ROASTER_PICKS[r.id] || null;
  const vals = [
    q(r.id), num(r.serial), q(r.name), q(r.origin), q(r.method), q(r.ratio), q(r.ratioLabel),
    num(r.strength), q(r.description), q(r.story), q(r.bean), q(r.notes),
    json(r.ingredients || []), json(r.steps || []), json(r.methods || []), json(picks), ts(r.createdAt)
  ];
  return `  (${vals.join(', ')})`;
});

const sql = `-- ===== Brew Book — catalog seed (${SEED.length} recipes) =====
-- Generated by scripts/export-seed-sql.js — do not edit by hand; re-run the
-- script after changing js/data.js. Safe to run repeatedly: on-conflict it
-- refreshes the existing catalog rows, so this doubles as a "sync" script.

insert into public.recipes
  (${cols.join(', ')})
values
${rows.join(',\n')}
on conflict (id) do update set
  serial = excluded.serial,
  name = excluded.name,
  origin = excluded.origin,
  method = excluded.method,
  ratio = excluded.ratio,
  ratio_label = excluded.ratio_label,
  strength = excluded.strength,
  description = excluded.description,
  story = excluded.story,
  bean = excluded.bean,
  notes = excluded.notes,
  ingredients = excluded.ingredients,
  steps = excluded.steps,
  methods = excluded.methods,
  roaster_picks = excluded.roaster_picks;
`;

const outPath = path.join(__dirname, '..', 'supabase', 'seed.sql');
fs.writeFileSync(outPath, sql);
console.log(`Wrote ${outPath} — ${SEED.length} recipes, ${sql.length} bytes.`);
